require('tsx/cjs');
const assert=require('node:assert/strict');
const {ConfigManager}=require('../assets/scripts/core/ConfigManager.ts');
const {RunSession}=require('../assets/scripts/core/RunSession.ts');
const {readRunSave}=require('../assets/scripts/core/ShopSave.ts');
const tools=require('../tools/run-simulation.ts'),input=tools.loadRunInputs();
const cfg=new ConfigManager();cfg.setUnits(input.units);cfg.setSkills(input.skills);cfg.setBattle(input.battle);cfg.setEquipment(input.equipment);
const options={...tools.loadEnemyGenerationInputs(),...tools.loadFormationInputs(),...tools.loadEquipmentInputs(),runSeed:1028,stageCount:6};
const s=new RunSession(cfg,input.run,input.waves,options);s.level.level=7;
if(s.pendingOpeningEncounter)s.chooseOpeningEncounter(s.openingEncounterOptions[0].id);
const summon=()=>s.createPreview().sim.units.find(u=>u.side===0&&u.cfg.summonOnly);
assert.equal(summon(),undefined);assert.equal(s.moveSummon({x:1,y:0}).error,'no_summon');
const members=['redhorn_imp','hellflame_hound','saien','infernal_axe_guard','raven_succubus','crimson_gunslinger','thornchain_succubus'];
const pieces=members.map((id,i)=>{const u=s.owned.addToBench(id,12);assert.ok(u);assert.ok(s.pool.take(id));u.location='board';u.x=i;u.y=0;return u;});
assert.equal(summon().star,3);assert.equal(s.owned.onBoard().length,7);
assert.ok(s.moveSummon({x:6,y:2}).ok);assert.deepEqual(summon().pos,{x:6,y:2});
const original={x:pieces[0].x,y:pieces[0].y};
assert.ok(s.moveSummon(original).ok);assert.deepEqual(summon().pos,original);assert.deepEqual({x:pieces[0].x,y:pieces[0].y},{x:6,y:2});
assert.ok(s.moveUnit(pieces[0].uid,{location:'board',...original}).ok);assert.deepEqual(summon().pos,{x:6,y:2});
for(const p of [{x:-1,y:0},{x:0,y:cfg.battle.ownRows},{x:.5,y:0}])assert.equal(s.moveSummon(p).error,'invalid_position');
for(const u of pieces.slice(2)){u.location='bench';u.x=-1;u.y=members.indexOf(u.unitId);}
assert.equal(summon(),undefined,'deactivation removes preview summon');
pieces[2].location='board';pieces[2].x=2;pieces[2].y=0;
assert.equal(summon().star,1);assert.deepEqual(summon().pos,{x:6,y:2},'reactivation keeps chosen deployment');
const saved=s.snapshot();assert.deepEqual(readRunSave(saved).demonPosition,{x:6,y:2});
const restored=new RunSession(cfg,input.run,input.waves,{...options,save:saved});
assert.deepEqual(restored.createPreview().sim.units.find(u=>u.side===0&&u.cfg.summonOnly).pos,{x:6,y:2});
const sim=s.startBattle();assert.ok(sim);assert.deepEqual(sim.units.find(u=>u.side===0&&u.cfg.summonOnly).pos,{x:6,y:2});
assert.equal(s.moveSummon({x:5,y:2}).error,'fighting');
assert.equal(s.owned.onBoard().length,3,'summon never consumes population or enters ownership');
console.log('PASS demon preparation deployment: activation, tier changes, bidirectional swaps, legal cells, reactivation, current-save persistence and combat lock');
