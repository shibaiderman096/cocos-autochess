const assert=require('node:assert/strict'),path=require('node:path');
const h=require('./helpers/ui-harness.cjs');
const {WaveTransition}=h.load(path.resolve('assets/scripts/ui/WaveTransition.ts'));
const root=new h.Node('ui'),transition=new WaveTransition(root);
let covered=0,complete=0;
const start=()=>transition.play(()=>{covered++;assert.equal(transition.opacity.opacity,255,'board swaps only under full coverage');return {id:21,stage:3,round:1,name:'下一关'}},()=>complete++);
start();
for(let i=0;i<20&&covered===0;i++)transition.update(10);
assert.equal(covered,1);assert.equal(complete,0);assert.equal(transition.round.string,'3 - 1');
assert.equal(transition.root.active,true);assert.equal(transition.opacity.opacity,255);
transition.update(10);assert.equal(transition.opacity.opacity,255,'a long mobile frame cannot skip the destination hold');
for(let i=0;i<30;i++)transition.update(.1);
assert.equal(covered,1);assert.equal(complete,1);assert.equal(transition.root.active,false);
start();transition.stop();for(let i=0;i<50;i++)transition.update(.1);
assert.equal(covered,1);assert.equal(complete,1,'scene cleanup cancels pending callbacks');
console.log('PASS wave transition: coverage, visible destination under slow frames, one-shot swap/completion and cancellation');
